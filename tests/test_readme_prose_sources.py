# The sources archive itself is quotable for document-class claims: any
# figure in an archived primary (or the README's documented derivations of
# them) may appear in the email. PDFs are pre-extracted to *_extracted.txt;
# the news release is archived as HTML.
_ARCHIVE_GLOBS = [
    "docs/sources/*_extracted.txt",
    "docs/sources/*.md",
    "docs/sources/*/README.md",
    "docs/sources/miway_57000_hours_news_release_2024.html",
    "docs/citation-review.md",
    "docs/data-share/CODEBOOK.md",
    "docs/capacity-calibration-findings.md",
]


def _archive_corpus() -> str:
    parts = []
    for rel in _ARCHIVE_GLOBS:
        for p in sorted(_ROOT.glob(rel)):
            try:
                parts.append(p.read_text(encoding="utf-8"))
            except OSError:
                continue
    return "\n".join(parts)


def _email_checked_lines() -> list[str]:
    """The narrative body only — stop at the audit appendix, which describes
    the numbers rather than quoting them (and which the generator owns)."""
    text = _EMAIL.read_text(encoding="utf-8")
    return text.split("## What's in this email")[0].splitlines()


def test_email_document_claims_trace_to_archived_sources():
    """Every stable document-class number in the email body must appear in
    the sources archive (or a whitelisted derivation of it).

    Collector-window numbers (percent-of-capacity, n= sample sizes, ghost
    counts, lateness rates) are exempt: they are regenerated per window by
    the committed generator from committed CSVs — see module docstring.
    """
    corpus = _archive_corpus().replace(",", "")
    # Whitelisted derivations: (pattern-in-email, explanation, expected forms
    # in corpus). One line each — an unexplained derivation doesn't belong.
    derived_whitelist = [
        # 2024 TransLink boardings/journeys pair, derivation documented in
        # docs/sources/README.md (open-data sums vs published journeys).
        (r"1\.6\d?", "boardings/journey 2024", ("1.67", "1.73")),
        (r"400\s*million", "system boardings 2024", ("401", "401.8")),
        # The 2019 baseline band, triangulated in docs/sources/README.md.
        (r"\b54M\b", "triangulated 2019 baseline", ("54", "54.1", "54.5")),
    ]

    unexplained: list[str] = []
    for line in _email_checked_lines():
        # Document-class check: million/billion/M-suffixed figures only.
        # Collector-window percentages (42% full, 27.3% early, ...) are
        # regenerated every rebuild by scripts/build_councillor_email.py
        # from the committed obs/occupancy CSVs — they are guarded by the
        # committed generator + committed data, NOT by the archive corpus,
        # which would false-fail every window refresh. (Fabricated
        # percentages in a hand-edited draft are caught by review; the
        # CI-enforced path is the generator, which is committed.)
        for m in re.finditer(
            r"\d[\d,]*(?:\.\d+)?\s*(?:million|billion|M\b)", line, re.I
        ):
            tok = m.group(0).strip()
            bare = tok.replace(",", "")
            num = re.match(r"\d[\d,]*(?:\.\d+)?", bare).group(0)
            if re.fullmatch(r"\d{4}", num):  # years pass
                continue
            if num in corpus or bare in corpus:
                continue
            if any(
                re.fullmatch(pat, tok.strip("%M ")) for pat, _, _ in derived_whitelist
            ):
                continue
            if any(
                exp in corpus for _, _, exps in derived_whitelist for exp in exps
            ) and any(re.fullmatch(pat, num) for pat, _, _ in derived_whitelist):
                continue
            unexplained.append(f"{tok!r} <- {line.strip()[:120]!r}")

    assert not unexplained, (
        "councillor email quotes document-class numbers with no archived "
        "source (docs/sources/*_extracted.txt, *.md, news release). Either "
        "archive the primary or fix the email:\n" + "\n".join(unexplained[:15])
    )


def test_email_catch_fabricated_document_claim():
    """Guard the guard: a fabricated document-class number must fail."""
    # Poison value chosen to be absent from the archive corpus (asserted
    # when this gate was written; re-check if the corpus grows onto it).
    # Poison IN MEMORY: writing the committed draft (even with a restore)
    # races under xdist — a parallel worker can read the poisoned file.
    original = _EMAIL.read_text(encoding="utf-8")
    poisoned = original.replace(
        "Happy to share the full dataset",
        "MiWay carried 97.4 million boardings in 2017. Happy to share the full dataset",
        1,
    )
    assert "97.4 million" in poisoned
    corpus = _archive_corpus().replace(",", "")
    caught = False
    for line in poisoned.split("## What's in this email")[0].splitlines():
        for m in re.finditer(r"\d[\d,]*(?:\.\d+)?\s*million", line, re.I):
            num = re.match(r"\d[\d,]*(?:\.\d+)?", m.group(0)).group(0)
            if num == "97.4" and num not in corpus:
                caught = True
    assert caught, "fabricated document claim was not caught"


