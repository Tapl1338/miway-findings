"""Prose-check: README numbers must exist in a quotable source.

The README's findings section is the project's public face; its numbers
drifted once already (30.7% early quoted while the frozen data said 30.0%,
then the live mid-window API said 33.0% — three numbers for one truth).
This test fails CI when a headline number in the README's findings or
model-results sections is not present in (or consistent with) a quotable
source: the immutable findings snapshots, the pinned solver receipts, the
window-close weekly rollup, or the realized-waits snapshot.

Rules of the check (kept deliberately conservative to avoid false
positives that would teach people to ignore it):

* Only numbers in the two findings/model sections of the README are
  checked — the rest of the page (install commands, port numbers, panel
  descriptions) is not data.
* Percentages with sample sizes (e.g. "30.0% ... (n = 622,183)") are
  checked against the source corpora for BOTH the rate and the n.
* A number passes if it appears verbatim in any quotable source file, OR
  is derived by the whitelisted derivations below (weighted rollup mean,
  ghost ratio). Derivations must stay whitelisted — a derivation that
  can't be explained in one line doesn't belong in the README.
* Ranges ("38–41 min", "51–64%") pass when both endpoints are quotable.

Sources considered quotable:
* docs/findings/*.md (immutable snapshots — the DRAFT skeleton's TODOs are
  never numbers, so drafts can't leak quotes)
* docs/runs/*.md (solver receipts, verdicts — pinned artifacts)
* docs/sources/gtfs_archive/MANIFEST.md (feed vintages)
* backend/app/data/weekly_rollup.csv (window-close deduped, machine-read)
* backend/app/data/realized_waits.csv (pinned realized-waits snapshot)

NOT quotable: the live API, live CSVs mid-window, memory, vibes.

Scope added 2026-09-04 — two more public surfaces:

* ``docs/councillor-email-draft.md``: the email mixes two number classes.
  *Document claims* (58.4M boardings, 240.9M journeys, 57,000 hours, the
  boardings/journey pair) are stable and enforced against the sources
  archive below. *Collector-window numbers* (crowding %, n= counts, ghost
  rates) are regenerated by ``scripts/build_councillor_email.py`` after
  every window — pinning them here would false-fail each rebuild, so they
  are exempt by design and guarded instead by the committed generator plus
  the committed data artifacts it reads. The boundary is the Key-numbers
  table's own source column: rows citing ``.csv``/``.json`` artifacts are
  collector class; everything else is document class.
* ``GET /api/peers``: every figure the endpoint serves is either read from
  committed peer CSVs, a module constant, or MiWay's published annual
  series — each must match its quotable source. The MiWay 2019 slot must
  stay None (never published) and the journey-stats contrast must keep its
  identifiability wording.
"""

from __future__ import annotations

import re
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[2]
README = _ROOT / "README.md"

# Findings + model sections: everything between these headings is checked.
_SECTION_START = "## Findings presented to the City"
_SECTION_END = "## Quick start"

_QUOTABLE_GLOBS = [
    _ROOT / "docs" / "findings" / "*.md",
    _ROOT / "docs" / "runs" / "*.md",
    _ROOT / "docs" / "sources" / "gtfs_archive" / "MANIFEST.md",
]


def _checked_text() -> str:
    text = README.read_text(encoding="utf-8")
    start = text.index(_SECTION_START)
    end = text.index(_SECTION_END)
    return text[start:end]


def _corpus() -> str:
    parts = []
    for pattern in _QUOTABLE_GLOBS:
        for p in sorted(_ROOT.glob(str(pattern.relative_to(_ROOT)))):
            parts.append(p.read_text(encoding="utf-8"))
    return "\n".join(parts)


def _rollup_derived_numbers() -> set[str]:
    """Numbers derivable from the window-close rollup, formatted as the
    README formats them. One whitelisted derivation per line."""
    import csv

    path = _ROOT / "backend" / "app" / "data" / "weekly_rollup.csv"
    if not path.exists():
        return set()
    with path.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        return set()
    out: set[str] = set()
    n_total = sum(int(float(r["n_recorded"] or 0)) for r in rows)
    if n_total:
        early = (
            sum(
                float(r["pct_early_gt2"] or 0) * int(float(r["n_recorded"] or 0))
                for r in rows
            )
            / n_total
        )
        out.add(f"{early:.1f}%")
        out.add(f"n = {n_total:,}")
    ghosts = sum(int(float(r["ghost_trips"] or 0)) for r in rows)
    verifiable = sum(int(float(r["verifiable_trips"] or 0)) for r in rows)
    if ghosts:
        out.add(f"1 in {round(verifiable / ghosts)}")
    return out


def _realized_waits_derived() -> set[str]:
    """Numbers derivable from the realized-waits snapshot (p90 band,
    missed-share band, pairing count). Whitelisted derivations only."""
    import csv

    path = _ROOT / "backend" / "app" / "data" / "realized_waits.csv"
    if not path.exists():
        return set()
    with path.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    out: set[str] = set()
    band = [
        r
        for r in rows
        if 38 <= float(r["realized_p90_min"]) <= 41
        and 0.51 <= float(r["realized_missed_share"]) <= 0.66
    ]
    out.add(str(len(band)))  # pairing count in the quoted band
    if band:
        lo = round(min(float(r["realized_missed_share"]) for r in band) * 100)
        hi = round(max(float(r["realized_missed_share"]) for r in band) * 100)
        out.add(f"{lo}–{hi}%")
        out.add(f"{lo}-{hi}%")
    return out


def _extract_claims(text: str) -> list[tuple[str, str]]:
    """(number-as-written, context-line) pairs worth checking."""
    claims = []
    for line in text.splitlines():
        # Skip lines that are explicitly historical/presented labels.
        if "presented" in line.lower() or "v1:" in line:
            continue
        for m in re.finditer(
            r"\d[\d,]*(?:\.\d+)?(?:\s*[–-]\s*\d[\d,]*(?:\.\d+)?)?(?:\s*%)?", line
        ):
            tok = m.group(0).strip()
            # Filter obvious non-data: years, section numbers, small ints
            # with units like "12 routes" stay (they are data claims).
            claims.append((tok, line.strip()[:120]))
    return claims


def test_readme_findings_numbers_exist_in_quotable_sources():
    text = _checked_text()
    corpus = _corpus()
    derived = _rollup_derived_numbers() | _realized_waits_derived()

    # Numbers with units/words that are claims, not dates or headings.
    # A claim must contain a %, a decimal, a "1 in N", or be >= 3 digits —
    # anything else (route numbers, "277", "2x2") is too generic to police
    # mechanically and is covered by review.
    unexplained: list[str] = []
    for tok, line in _extract_claims(text):
        if not (
            "%" in tok
            or re.search(r"^\d[\d,]*\.\d+$", tok)
            or re.match(r"^1 in \d", tok)
            or re.fullmatch(r"\d{3,}[\d,]*", tok)
        ):
            continue
        # Both endpoints of a range must be findable; allow the range token.
        parts = re.split(r"\s*[–-]\s*", tok)
        for part in parts:
            part = part.strip().rstrip("%").replace(",", "")
            if not part or re.fullmatch(r"\d{4}", part):  # years/dates pass
                continue
            if part in corpus.replace(",", "") or tok in corpus:
                continue
            if any(part in d.replace(",", "") for d in derived):
                continue
            unexplained.append(f"{tok!r} <- line: {line!r}")

    assert not unexplained, (
        "README quotes numbers with no quotable source "
        "(docs/findings, docs/runs, MANIFEST, weekly rollup, realized waits). "
        "Either add the number to a snapshot/receipt, or fix the README:\n"
        + "\n".join(unexplained[:15])
    )


def test_check_catches_a_fabricated_number():
    """Guard the guard: inject a fake number and prove the check fails."""
    original = README.read_text(encoding="utf-8")
    # Sentinel must be distinctive: committed run CSVs carry float artifacts
    # like "...9999999999998", and the corpus test is a substring match — a
    # 999999999 sentinel accidentally appeared quotable after those runs
    # landed (2026-09-17), silently disarming this guard-the-guard test.
    # 999999991 does not occur in any quotable source.
    poisoned = original.replace(
        _SECTION_END,
        "999999991 unexplained\n\n" + _SECTION_END,
        1,
    )
    assert "999999991" in poisoned
    README.write_text(poisoned, encoding="utf-8")
    try:
        # Re-run the check logic inline (can't call pytest recursively).
        corpus = _corpus()
        derived = _rollup_derived_numbers() | _realized_waits_derived()
        checked = poisoned[
            poisoned.index(_SECTION_START) : poisoned.index(_SECTION_END)
        ]
        found = False
        for tok, _line in _extract_claims(checked):
            if re.fullmatch(r"\d{3,}[\d,]*", tok) and tok not in corpus:
                if not any(tok.replace(",", "") in d for d in derived):
                    found = True
                    break
        assert found, "the check did NOT catch a fabricated number"
    finally:
        README.write_text(original, encoding="utf-8")


def test_v2_draft_contains_no_quotable_numbers_yet():
    """The draft skeleton must be TODO-only — a draft that already carries
    numbers would let prose quote it as if frozen."""
    draft = _ROOT / "docs" / "findings" / "findings-v2-post-sept7-DRAFT.md"
    if not draft.exists():
        return  # renamed after the window closes; check no longer applies
    text = draft.read_text(encoding="utf-8")
    assert "STATUS: DRAFT SKELETON" in text
    # No frozen-style rate claims: no "XX.X%" outside v1-baseline lines
    # (v1 references are quotable — they point at the immutable v1 file).
    for line in text.splitlines():
        if (
            "v1:" in line
            or "v1 " in line
            or "30.0%" in line
            or "37%" in line
            or "README resync" in line  # quotes other quotable sources
        ):
            continue
        if re.search(r"\d\d\.\d%|\d\d%", line) and "TODO" not in line:
            raise AssertionError(
                f"draft carries an unfrozen rate claim: {line.strip()!r}"
            )


