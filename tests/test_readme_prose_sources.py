def _peers_payload() -> dict:
    import sys

    sys.path.insert(0, str(_ROOT / "backend"))
    from fastapi.testclient import TestClient

    from app.main import app

    return TestClient(app).get("/api/peers").json()


def test_peers_payload_numbers_match_committed_data():
    """Every figure /api/peers serves must match a committed artifact or an
    archived primary. MiWay's 2019 slot must stay None, and the journey-stats
    contrast must keep its identifiability wording."""
    data = _peers_payload()

    # TransLink card numbers must equal the committed demo CSV sums.
    import csv

    ridership = (
        _ROOT / "backend" / "app" / "data" / "peers" / "translink" / "ridership.csv"
    )
    if ridership.exists() and data.get("translink"):
        with ridership.open(encoding="utf-8") as f:
            rows = [r for r in csv.DictReader(f) if r.get("tspr_year") == "2024"]
        committed_total = sum(int(float(r["boardings"])) for r in rows)
        assert data["translink"]["total_boardings"] == committed_total

    # The boardings-per-journey figure must match the archived derivation.
    js = (data.get("translink") or {}).get("journey_stats") or {}
    readme = (_ROOT / "docs" / "sources" / "README.md").read_text(encoding="utf-8")
    if js.get("boardings_per_journey") is not None:
        assert f"{js['boardings_per_journey']:.2f}" in readme
        assert "1.73" in js.get("corroborating_pair", "")

    # MiWay annual series: every point must cite a source, 2019 stays None,
    # and published values must match the archived primary documents.
    series = {p["year"]: p for p in data["miway_annual_series"]}
    assert series[2019]["boardings_millions"] is None
    corpus = _archive_corpus().replace(",", "")
    for year, p in series.items():
        assert p["source"], f"{year} point has no source"
        val = p["boardings_millions"]
        if val is None:
            continue
        formatted = f"{val:.1f}" if val % 1 else str(int(val))
        assert formatted in corpus, (
            f"peers series {year}={val}M not found in archived sources"
        )

    # Journey-stats honesty: MiWay null with the derivability reason.
    mjs = (data.get("miway") or {}).get("journey_stats") or {}
    assert mjs.get("boardings_per_journey") is None
    assert "deriv" in mjs.get("source", "").lower()

    # FAO-anchored recovery index: every index value must be printed in the
    # archived derivation, and the FAO Ontario rows must match its table.
    idx = data.get("miway_recovery_index") or {}
    if idx:
        fao_readme = (
            (_ROOT / "docs" / "sources" / "fao-transit-2024" / "README.md")
            .read_text(encoding="utf-8")
            .replace(",", "")
        )
        for pt in idx["points"]:
            assert f"{pt['index_2019']:.1f}" in fao_readme.replace(",", ""), (
                f"recovery index {pt['year']}={pt['index_2019']} not in the "
                "FAO derivation"
            )
        ctx = data.get("ontario_context") or {}
        for row in ctx.get("rows", []):
            for year, val in row["trips_millions"].items():
                assert f"{val}" in fao_readme.replace(",", ""), (
                    f"ontario row {row['agency']} {year}={val} not in the FAO table"
                )
        # The as-published series keeps its honest 2019 hole alongside.
        ttc_readme = (
            (_ROOT / "docs" / "sources" / "ttc-surface-route-stats" / "README.md")
            .read_text(encoding="utf-8")
            .replace(",", "")
        )
        for pt in (data.get("ttc_surface_fall_index") or {}).get("points", []):
            assert f"{pt['index_2019']:.1f}" in ttc_readme.replace(",", ""), (
                f"ttc index {pt['year']}={pt['index_2019']} not in the Munro derivation"
            )
        # Service-supply rows: raw values and pct changes must be printed in
        # the supply derivation (or its quoted Munro/TSPR sources).
        supply_readme = (
            (_ROOT / "docs" / "sources" / "miway-service-supply" / "README.md")
            .read_text(encoding="utf-8")
            .replace(",", "")
            .replace("\u2212", "-")
        )
        for row in (data.get("service_supply") or {}).get("rows", []):
            for val in (row.get("value_then"), row.get("value_now")):
                if val is not None:
                    assert f"{val}" in supply_readme, (
                        f"supply row {row['agency']} value {val} not in the "
                        "supply derivation"
                    )
            if row.get("pct_change") is not None:
                assert f"{row['pct_change']}" in supply_readme, (
                    f"supply row {row['agency']} pct {row['pct_change']} not "
                    "in the supply derivation"
                )


def test_frozen_sent_email_is_byte_exact():
    """The record of what was actually emailed to Councillor Sample on
    2026-08-25 must never change. It was extracted byte-exact from commit
    b296ac1 ("email sent to Councillor Sample 2026-08-25 10:13") into
    docs/runs/sent-20260825-reid.txt after the regenerated draft was
    mistaken for the send record. Any edit to the frozen file — even one
    character — fails here, and the sha256 must match the pinned value."""
    import hashlib

    sent = _ROOT / "docs" / "runs" / "sent-20260825-reid.txt"
    assert sent.exists(), "frozen sent-text artifact is missing"
    data = sent.read_bytes()
    assert hashlib.sha256(data).hexdigest() == (
        "7f62eb48cb2075d5511ba143b4d76a62fee0e7c1c8b9009144da2957d083653e"
    ), "frozen sent text was modified — restore it from commit b296ac1"
    # Spot-check the sent-only anchors: the pre-Sept-7 reliability window
    # ("9 days", "866 of 28,079", "3.1%") is what Reid received; the
    # regenerated draft says 19 days / 437 / 0.6%.
    text = data.decode("utf-8")
    assert "866 of 28,079 verifiable trips" in text
    assert "9 days of sampling" in text
    assert "437 of 73,980" not in text, (
        "frozen sent text contains post-send numbers — it was overwritten"
    )
